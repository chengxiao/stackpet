#pragma once
#include <lvgl.h>

namespace stackpet::ui {

// Full Chinese text font (~7000 common chars, 20 px) loaded from the assets partition
// (font_puhui_common_20_4.bin, packed by build_default_assets.py). Falls back to Montserrat 20 if missing.
// Use it for arbitrary text (results, web "speak" text). Call with the LVGL lock held.
const lv_font_t* fontCn20();
// fontCn20() made from the CN font file where the assets partition is mapped now, the same address and size (its glyphs
// stay in the partition: the AI agent may download new assets and map them again)
bool fontCn20Current();

// Large title fonts generated by tools/gen_stackpet_fonts.sh. They only contain ASCII plus the CJK
// characters that appear in the StackPet sources (main/stackpet, main/apps/app_remote|app_freeze|app_spin),
// so re-run the script after adding new Chinese UI strings.
const lv_font_t* fontTitle28();
const lv_font_t* fontTitle44();

}  // namespace stackpet::ui
